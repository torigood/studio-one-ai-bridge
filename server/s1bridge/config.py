"""Filesystem locations used by the server and setup.py, in one place.

Every path can be overridden with an environment variable. Defaults are the
Studio One 5 locations on macOS (the only tested platform). The Windows
defaults are best guesses and untested.

  S1BRIDGE_APP            Studio One application   /Applications/Studio One 5.app
  S1BRIDGE_SETTINGS_DIR   Studio One settings      ~/Library/Application Support/PreSonus/Studio One 5
  S1BRIDGE_USER_CONTENT   Studio One user content  ~/Music/Studio One 5   ($USERCONTENT inside Studio One)
  S1BRIDGE_SONGS          songs                    <user content>/Songs
  S1BRIDGE_SOUNDSETS      sound sets               <user content>/Sound Sets
  S1BRIDGE_PRESETS        user presets             <user content>/Presets
  S1BRIDGE_MAILBOX        bridge mailbox           <user content>/AIBridge
  S1BRIDGE_DATA_DIR       this project's data      ~/Library/Application Support/studio-one-ai-bridge
  S1BRIDGE_CATALOG        command catalog          <data dir>/commands.json
  S1BRIDGE_ANALYSIS_PYTHON  Python with numpy for audio analysis

The mailbox must match bridge/src/bridge.js (local://$USERCONTENT/AIBridge).
"""
import os
import sys

IS_MAC = sys.platform == "darwin"
IS_WINDOWS = sys.platform.startswith("win")

# server/s1bridge/config.py -> project root (only meaningful when run from a checkout)
PROJECT_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def _env(name, default):
    v = os.environ.get(name)
    return os.path.expanduser(v) if v else default


def _home(*parts):
    return os.path.join(os.path.expanduser("~"), *parts)


if IS_WINDOWS:
    _APPDATA = os.environ.get("APPDATA") or _home("AppData", "Roaming")
    _APP = os.path.join(os.environ.get("ProgramFiles", r"C:\Program Files"), "PreSonus", "Studio One 5")
    _SETTINGS = os.path.join(_APPDATA, "PreSonus", "Studio One 5")
    _USER_CONTENT = _home("Documents", "Studio One 5")
    _DATA = os.path.join(_APPDATA, "studio-one-ai-bridge")
else:
    _APP = "/Applications/Studio One 5.app"
    _SETTINGS = _home("Library", "Application Support", "PreSonus", "Studio One 5")
    _USER_CONTENT = _home("Music", "Studio One 5")
    _DATA = _home("Library", "Application Support", "studio-one-ai-bridge")

APP = _env("S1BRIDGE_APP", _APP)
SETTINGS_DIR = _env("S1BRIDGE_SETTINGS_DIR", _SETTINGS)
USER_CONTENT = _env("S1BRIDGE_USER_CONTENT", _USER_CONTENT)

SONGS_ROOT = _env("S1BRIDGE_SONGS", os.path.join(USER_CONTENT, "Songs"))
SOUNDSETS_DIR = _env("S1BRIDGE_SOUNDSETS", os.path.join(USER_CONTENT, "Sound Sets"))
USER_PRESETS_DIR = _env("S1BRIDGE_PRESETS", os.path.join(USER_CONTENT, "Presets"))
MAILBOX = _env("S1BRIDGE_MAILBOX", os.path.join(USER_CONTENT, "AIBridge"))
EXTENSIONS_DIR = os.path.join(SETTINGS_DIR, "Extensions")
USER_DEVICES_DIR = os.path.join(SETTINGS_DIR, "User Devices")

DATA_DIR = _env("S1BRIDGE_DATA_DIR", _DATA)
CATALOG = _env("S1BRIDGE_CATALOG", os.path.join(DATA_DIR, "commands.json"))
# Catalog generated by older versions inside the checkout; read if the default is missing.
LEGACY_CATALOG = os.path.join(PROJECT_ROOT, "catalog", "commands.json")


def app_resource(*parts):
    """Path inside the Studio One installation (macOS bundles keep resources under Contents/)."""
    return os.path.join(APP, "Contents", *parts) if IS_MAC else os.path.join(APP, *parts)


APP_PRESETS_DIR = app_resource("presets", "PreSonus")


def plugin_cache():
    """Studio One's plug-in cache (Plugins-en.settings). ARM64 first, as before; then any arch folder."""
    preferred = os.path.join(SETTINGS_DIR, "ARM64", "Plugins-en.settings")
    if os.path.isfile(preferred) or not os.path.isdir(SETTINGS_DIR):
        return preferred
    for name in sorted(os.listdir(SETTINGS_DIR)):
        p = os.path.join(SETTINGS_DIR, name, "Plugins-en.settings")
        if os.path.isfile(p):
            return p
    return preferred


def catalog_path():
    """Catalog to read: S1BRIDGE_CATALOG / data dir, else one left in the checkout."""
    if os.path.isfile(CATALOG) or "S1BRIDGE_CATALOG" in os.environ:
        return CATALOG
    return LEGACY_CATALOG if os.path.isfile(LEGACY_CATALOG) else CATALOG


def analysis_python():
    """Interpreter for s1bridge.audio_analysis (needs numpy): env, then the checkout's .venv,
    then the interpreter running the server (works when installed with the `analysis` extra)."""
    if os.environ.get("S1BRIDGE_ANALYSIS_PYTHON"):
        return os.environ["S1BRIDGE_ANALYSIS_PYTHON"]
    venv = os.path.join(PROJECT_ROOT, ".venv", "Scripts" if IS_WINDOWS else "bin",
                        "python.exe" if IS_WINDOWS else "python")
    return venv if os.path.exists(venv) else sys.executable
